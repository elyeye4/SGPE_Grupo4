-- =========================================================
-- 1. ADMINISTRACIÓN INICIAL
-- =========================================================

DROP DATABASE IF EXISTS sgpe;

DROP USER IF EXISTS 'sgpe_app'@'%';
DROP USER IF EXISTS 'sgpe_consulta'@'%';

CREATE DATABASE sgpe
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_unicode_ci;

CREATE USER 'sgpe_app'@'%' IDENTIFIED BY 'Sgpe_App_2026.';
CREATE USER 'sgpe_consulta'@'%' IDENTIFIED BY 'Sgpe_Consulta_2026.';

GRANT SELECT, INSERT, UPDATE, DELETE ON sgpe.* TO 'sgpe_app'@'%';
GRANT SELECT ON sgpe.* TO 'sgpe_consulta'@'%';
FLUSH PRIVILEGES;

USE sgpe;

-- =========================================================
-- 2. CREACIÓN DE TABLAS
-- =========================================================

CREATE TABLE FIDE_ESTADO_TB (
    ID_ESTADO INT NOT NULL AUTO_INCREMENT,
    NOMBRE_ESTADO VARCHAR(40) NOT NULL,
    DESCRIPCION_ESTADO VARCHAR(150),
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_ESTADO),
    UNIQUE (NOMBRE_ESTADO)
);

CREATE TABLE FIDE_ROL_TB (
    ID_ROL INT NOT NULL AUTO_INCREMENT,
    NOMBRE_ROL VARCHAR(30) NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_ROL),
    UNIQUE (NOMBRE_ROL),
    CONSTRAINT FK_ROL_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_CATEGORIA_TB (
    ID_CATEGORIA INT NOT NULL AUTO_INCREMENT,
    NOMBRE_CATEGORIA VARCHAR(50) NOT NULL,
    DESCRIPCION_CATEGORIA VARCHAR(150),
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_CATEGORIA),
    UNIQUE (NOMBRE_CATEGORIA),
    CONSTRAINT FK_CATEGORIA_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_USUARIO_TB (
    ID_USUARIO INT NOT NULL AUTO_INCREMENT,
    USERNAME VARCHAR(30) NOT NULL,
    CONTRASENA VARCHAR(512) NOT NULL,
    NOMBRE_USUARIO VARCHAR(40) NOT NULL,
    APELLIDO1 VARCHAR(40) NOT NULL,
    APELLIDO2 VARCHAR(40),
    CORREO VARCHAR(100) NOT NULL,
    TELEFONO VARCHAR(25),
    ID_ROL INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_USUARIO),
    UNIQUE (USERNAME),
    UNIQUE (CORREO),
    INDEX NDX_USUARIO_USERNAME (USERNAME),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL)
        REFERENCES FIDE_ROL_TB(ID_ROL),
    CONSTRAINT FK_USUARIO_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_EQUIPO_TB (
    ID_EQUIPO INT NOT NULL AUTO_INCREMENT,
    NOMBRE_EQUIPO VARCHAR(80) NOT NULL,
    DESCRIPCION_EQUIPO VARCHAR(250),
    RUTA_IMAGEN VARCHAR(1024),
    ID_CATEGORIA INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_EQUIPO),
    CONSTRAINT FK_EQUIPO_CATEGORIA FOREIGN KEY (ID_CATEGORIA)
        REFERENCES FIDE_CATEGORIA_TB(ID_CATEGORIA),
    CONSTRAINT FK_EQUIPO_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_PRESTAMO_TB (
    ID_PRESTAMO INT NOT NULL AUTO_INCREMENT,
    FECHA_SOLICITUD TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_INICIO DATE NOT NULL,
    FECHA_DEVOLUCION_LIMITE DATE NOT NULL,
    FECHA_APROBACION DATETIME NULL,
    FECHA_ENTREGA DATETIME NULL,
    OBSERVACIONES_PRESTAMO VARCHAR(250),
    ID_USUARIO_SOLICITANTE INT NOT NULL,
    ID_USUARIO_ADMINISTRADOR INT NULL,
    ID_EQUIPO INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_PRESTAMO),
    INDEX NDX_PRESTAMO_SOLICITANTE (ID_USUARIO_SOLICITANTE),
    INDEX NDX_PRESTAMO_ADMIN (ID_USUARIO_ADMINISTRADOR),
    INDEX NDX_PRESTAMO_EQUIPO (ID_EQUIPO),
    CONSTRAINT CHK_PRESTAMO_FECHAS CHECK (FECHA_DEVOLUCION_LIMITE >= FECHA_INICIO),
    CONSTRAINT FK_PRESTAMO_SOLICITANTE FOREIGN KEY (ID_USUARIO_SOLICITANTE)
        REFERENCES FIDE_USUARIO_TB(ID_USUARIO),
    CONSTRAINT FK_PRESTAMO_ADMIN FOREIGN KEY (ID_USUARIO_ADMINISTRADOR)
        REFERENCES FIDE_USUARIO_TB(ID_USUARIO),
    CONSTRAINT FK_PRESTAMO_EQUIPO FOREIGN KEY (ID_EQUIPO)
        REFERENCES FIDE_EQUIPO_TB(ID_EQUIPO),
    CONSTRAINT FK_PRESTAMO_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_DEVOLUCION_TB (
    ID_DEVOLUCION INT NOT NULL AUTO_INCREMENT,
    ID_PRESTAMO INT NOT NULL,
    FECHA_DEVOLUCION_REAL DATETIME NOT NULL,
    OBSERVACIONES_DEVOLUCION VARCHAR(250),
    ID_USUARIO_ADMINISTRADOR INT NOT NULL,
    ID_ESTADO INT NOT NULL,
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_MODIFICACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_DEVOLUCION),
    UNIQUE (ID_PRESTAMO),
    CONSTRAINT FK_DEVOLUCION_PRESTAMO FOREIGN KEY (ID_PRESTAMO)
        REFERENCES FIDE_PRESTAMO_TB(ID_PRESTAMO),
    CONSTRAINT FK_DEVOLUCION_ADMIN FOREIGN KEY (ID_USUARIO_ADMINISTRADOR)
        REFERENCES FIDE_USUARIO_TB(ID_USUARIO),
    CONSTRAINT FK_DEVOLUCION_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

CREATE TABLE FIDE_MOVIMIENTO_TB (
    ID_MOVIMIENTO INT NOT NULL AUTO_INCREMENT,
    ID_PRESTAMO INT NOT NULL,
    ID_USUARIO INT NOT NULL,
    TIPO_MOVIMIENTO VARCHAR(50) NOT NULL,
    DESCRIPCION_MOVIMIENTO VARCHAR(250),
    ID_ESTADO INT NOT NULL,
    FECHA_MOVIMIENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_MOVIMIENTO),
    INDEX NDX_MOVIMIENTO_PRESTAMO (ID_PRESTAMO),
    CONSTRAINT FK_MOVIMIENTO_PRESTAMO FOREIGN KEY (ID_PRESTAMO)
        REFERENCES FIDE_PRESTAMO_TB(ID_PRESTAMO),
    CONSTRAINT FK_MOVIMIENTO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES FIDE_USUARIO_TB(ID_USUARIO),
    CONSTRAINT FK_MOVIMIENTO_ESTADO FOREIGN KEY (ID_ESTADO)
        REFERENCES FIDE_ESTADO_TB(ID_ESTADO)
);

